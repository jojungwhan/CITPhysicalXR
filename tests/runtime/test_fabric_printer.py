@pytest.mark.asyncio
async def test_start_transport_failure_is_non_retryable_unknown_outcome(
    tmp_path: Path,
) -> None:
    transport = FakeTransport()
    printer, _slicer = service(tmp_path, transport, locked=False)
    source = await printer.stage_source(
        file_name="demo.stl",
        media_type="model/stl",
        content=b"solid demo\nendsolid demo\n",
    )
    sliced = await printer.slice_source(source.artifactId, "k1-max-0.4-pla-standard")
    artifact = sliced.snapshot.gcodeArtifacts[0]
    await printer.upload_artifact(artifact.artifactId)
    intent = await printer.prepare_start(artifact.artifactId, actor_id="instructor-a")
    transport.start_error = PrinterOutcomeUnknownError(
        "PRINTER_START_OUTCOME_UNKNOWN",
        "unknown",
        status_code=502,
    )

    with pytest.raises(PrinterOutcomeUnknownError):
        await printer.start_artifact(
            artifact.artifactId,
            actor_id="instructor-a",
            confirmation_token=intent.confirmationToken,
        )
    with pytest.raises(PrinterError, match="expired or does not match"):
        await printer.start_artifact(
            artifact.artifactId,
            actor_id="instructor-a",
            confirmation_token=intent.confirmationToken,
        )

    assert len(transport.starts) == 1


@pytest.mark.asyncio
async def test_moonraker_upload_forces_print_false(tmp_path: Path) -> None:
    requests: list[tuple[str, str, bytes | None]] = []

    async def request(
        method: str,
        url: str,
        _headers: Mapping[str, str],
        body: bytes | None,
        _request_timeout: float,
    ) -> tuple[int, bytes]:
        requests.append((method, url, body))
        return (
            201,
            b'{"result":{"item":{"path":"cit-test.gcode"},"print_started":false}}',
        )

    path = tmp_path / "test.gcode"
    path.write_bytes(b"; generated by Creality Print\nSTART_PRINT\n")
    transport = MoonrakerTransport(
        IPv4Address("192.0.2.10"),
        7125,
        request=request,
    )

    await transport.upload(path, remote_name="cit-test.gcode", checksum="a" * 64)

    assert requests[0][0] == "POST"
    assert requests[0][1] == "http://192.0.2.10:7125/server/files/upload"
    payload = requests[0][2]
    assert payload is not None
    assert b'name="print"' in payload
    assert b"\r\n\r\nfalse\r\n" in payload
    assert b"\r\n\r\ntrue\r\n" not in payload


def test_printer_api_stays_locked_and_audits_local_staging(tmp_path: Path) -> None:
    transport = FakeTransport(PrinterState.PRINTING)
    printer, _slicer = service(tmp_path, transport, locked=True)
    identity = FabricBootstrapIdentity(
        identity_id="admin-printer",
        token=ADMIN_TOKEN,
        actor_type="administrator",
        roles=("administrator",),
        permissions=tuple(sorted(FABRIC_PERMISSIONS)),
    )

    with TestClient(
        create_fabric_app(
            database_path=tmp_path / "fabric.sqlite3",
            clock=lambda: NOW,
            fabric_bootstrap_identities=(identity,),
            printer_service=printer,
            maintenance_interval=None,
        )
    ) as client:
        status = client.get("/api/v1/fabric/printer", headers=ADMIN_HEADERS)
        staged = client.post(
            "/api/v1/fabric/printer/sources",
            headers={
                **ADMIN_HEADERS,
                "Content-Type": "model/stl",
                "X-CIT-Filename": quote("교실 모형.stl"),
            },
            content=b"solid lesson\nendsolid lesson\n",
        )
        assert staged.status_code == 200, staged.text
        denied_slice = client.post(
            f"/api/v1/fabric/printer/sources/{staged.json()['artifactId']}/slice",
            headers=ADMIN_HEADERS,
            json={"profileId": "k1-max-0.4-pla-standard"},
        )
        audit = client.get("/api/v1/fabric/audit?limit=50", headers=ADMIN_HEADERS)

    assert status.status_code == 200
    assert status.json()["state"] == "current_print_locked"
    assert staged.status_code == 200
    assert staged.json()["fileName"] == "교실 모형.stl"
    assert denied_slice.status_code == 409
    assert denied_slice.json()["code"] == "PRINTER_CURRENT_PRINT_LOCKED"
    assert transport.status_calls == 0
    actions = [record["action"] for record in audit.json()]
    assert "fabric.printer.source.stage" in actions
    assert "fabric.printer.slice" in actions
