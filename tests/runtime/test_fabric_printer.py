class FakeTransport:
    def __init__(self, state: PrinterState = PrinterState.STANDBY) -> None:
        self.state = state
        self.status_calls = 0
        self.uploads: list[tuple[str, str]] = []
        self.starts: list[str] = []
        self.start_error: PrinterError | None = None

    async def status(self) -> TransportSnapshot:
        self.status_calls += 1
        return TransportSnapshot(
            state=self.state,
            checked_at=NOW,
            job=(
                PrinterJob(filename="protected-current-job.gcode", progressPercent=42.0)
                if self.state is PrinterState.PRINTING
                else None
            ),
        )

    async def upload(self, path: Path, *, remote_name: str, checksum: str) -> str:
        assert await asyncio.to_thread(path.is_file)
        self.uploads.append((remote_name, checksum))
        return remote_name

    async def start(self, remote_name: str) -> None:
        self.starts.append(remote_name)
        if self.start_error is not None:
            raise self.start_error


class FakeSlicer:
    def __init__(self) -> None:
        self.calls: list[tuple[Path, str]] = []

    async def slice(
        self,
        source: Path,
        *,
        output_directory: Path,
        profile: PrinterProfileConfiguration,
    ) -> Path:
        self.calls.append((source, profile.profile_id))

        def write_result() -> Path:
            output_directory.mkdir(parents=True)
            result = output_directory / "prepared.gcode"
            result.write_text(
                "; generated by Creality Print test double\n"
                "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60\n"
                "G28\n",
                encoding="utf-8",
            )
            return result

        return await asyncio.to_thread(write_result)


def profile(tmp_path: Path) -> PrinterProfileConfiguration:
    paths = [tmp_path / name for name in ("printer.json", "process.json", "filament.json")]
    for path in paths:
        path.write_text("{}", encoding="utf-8")
    return PrinterProfileConfiguration(
        profile_id="k1-max-0.4-pla-standard",
        display_name="K1 Max · PLA",
        printer_model="K1 Max",
        nozzle_diameter_mm=0.4,
        filament_name="Generic PLA",
        process_name="0.20 mm Standard",
        printer_settings=paths[0],
        process_settings=paths[1],
        filament_settings=paths[2],
    )


def service(
    tmp_path: Path,
    transport: FakeTransport,
    *,
    locked: bool,
    writes: bool = True,
) -> tuple[CrealityPrinterService, FakeSlicer]:
    slicer = FakeSlicer()
    configured = CrealityPrinterService(
        PrinterConfiguration(
            address=IPv4Address("172.30.1.55"),
            display_name="3D Printer",
            model="Creality K1 Max",
            staging_root=tmp_path / "stage",
            profiles=(profile(tmp_path),),
            moonraker_port=7125,
            network_monitoring_enabled=True,
            remote_writes_enabled=writes,
            current_print_locked=locked,
        ),
        transport=transport,
        slicer=slicer,
        clock=lambda: NOW,
    )
    return configured, slicer


@pytest.mark.asyncio
async def test_locked_snapshot_never_contacts_current_print(tmp_path: Path) -> None:
    transport = FakeTransport(PrinterState.PRINTING)
    printer, _slicer = service(tmp_path, transport, locked=True)

    snapshot = await printer.snapshot(refresh=True)

    assert snapshot.state is PrinterState.CURRENT_PRINT_LOCKED
    assert snapshot.operations.stageSource is True
    assert snapshot.operations.slice is False
    assert snapshot.operations.upload is False
    assert snapshot.operations.start is False
    assert snapshot.operations.lockReasonCode == "current_print"
    assert transport.status_calls == 0


@pytest.mark.asyncio
async def test_model_can_be_staged_locally_but_not_sliced_while_locked(
    tmp_path: Path,
) -> None:
    transport = FakeTransport(PrinterState.PRINTING)
    printer, slicer = service(tmp_path, transport, locked=True)

